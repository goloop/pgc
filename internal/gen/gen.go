// Package gen renders the generated Go source. It consumes a fully resolved
// model - names, Go types and SQL already decided - and owns nothing but the
// shape of the output. The golden tests in this package are the enforced
// specification of that shape.
package gen

import (
	"fmt"
	"go/format"
	"sort"
	"strconv"
	"strings"
)

// Input is one generated package.
type Input struct {
	Package string
	Enums   []Enum
	Models  []Model
	Files   []SrcFile
}

// Enum is a PostgreSQL enum rendered as a named string type with one
// constant per label.
type Enum struct {
	Name   string // Go type name
	DBName string // PostgreSQL type name
	Values []EnumValue
}

// EnumValue is one enum label.
type EnumValue struct {
	Name  string // Go constant name, e.g. OrderStatusPending
	Value string // database label, e.g. pending
}

// Model is a struct mirroring one database table.
type Model struct {
	Name   string // Go type name
	Table  string // database table name
	Fields []Field
}

// Field pairs a raw database column name with a resolved Go type. The Go
// field name is derived here, in one place, so every emitter agrees.
type Field struct {
	Name string // database name, e.g. created_at
	Type string // Go type expression, e.g. time.Time
}

// SrcFile is the queries of one source .sql file.
type SrcFile struct {
	Source  string // header path, e.g. queries/users.sql
	Out     string // output name, e.g. users.sql.go
	Queries []Query
}

// Query is one fully resolved query.
type Query struct {
	Name    string // exported Go name
	Doc     string // full doc sentence(s), starting with Name
	Command string // one, many, exec or execrows
	SQL     string
	Params  []Param
	Ret     Ret
}

// Param is one $N argument with its database-side name and Go type.
type Param struct {
	Name string // raw name, e.g. user_id or arg2
	Type string
}

// RetKind says what a query returns per row.
type RetKind int

const (
	RetNone   RetKind = iota // no result set
	RetScalar                // a single column
	RetModel                 // a full table row, scanned into a model
	RetRow                   // a projection, scanned into a per-query struct
)

// Ret describes a query's result shape. Type holds the scalar Go type or
// the struct name; Fields holds the columns in scan order (and, for RetRow,
// the struct definition).
type Ret struct {
	Kind   RetKind
	Type   string
	Fields []Field
}

// OutFile is one rendered file.
type OutFile struct {
	Name string
	Data []byte
}

// Render produces db.go, models.go (when there are models) and one file per
// source .sql file, each gofmt-formatted.
func Render(in Input) ([]OutFile, error) {
	var out []OutFile

	add := func(name string, src string) error {
		formatted, err := format.Source([]byte(src))
		if err != nil {
			return fmt.Errorf("gen: %s: %w (internal bug)", name, err)
		}
		out = append(out, OutFile{Name: name, Data: formatted})
		return nil
	}

	if err := add("db.go", emitDB(in.Package)); err != nil {
		return nil, err
	}
	if len(in.Models) > 0 || len(in.Enums) > 0 {
		if err := add("models.go", emitModels(in)); err != nil {
			return nil, err
		}
	}
	for _, f := range in.Files {
		if err := add(f.Out, emitFile(in.Package, f)); err != nil {
			return nil, err
		}
	}
	return out, nil
}

const header = "// Code generated by pgc. DO NOT EDIT.\n"

// emitDB renders the fixed plumbing: DBTX, Queries, New and WithTx.
func emitDB(pkg string) string {
	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "\npackage %s\n\n", pkg)
	b.WriteString(`import (
	"context"
	"database/sql"
)

// DBTX is the subset of database/sql methods the generated queries need.
// Both *sql.DB and *sql.Tx satisfy it, so the same Queries value works
// inside and outside a transaction.
type DBTX interface {
	ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error)
	QueryContext(ctx context.Context, query string, args ...any) (*sql.Rows, error)
	QueryRowContext(ctx context.Context, query string, args ...any) *sql.Row
}

// Queries exposes one method per SQL query. Create it once with New and
// share it: the value is immutable and safe for concurrent use.
type Queries struct {
	db DBTX
}

// New returns a Queries bound to db, which is usually *sql.DB.
func New(db DBTX) *Queries {
	return &Queries{db: db}
}

// WithTx returns a copy of q that runs its queries inside tx.
func (q *Queries) WithTx(tx *sql.Tx) *Queries {
	return &Queries{db: tx}
}
`)
	return b.String()
}

// emitModels renders one struct per table.
func emitModels(in Input) string {
	var types []string
	for _, m := range in.Models {
		for _, f := range m.Fields {
			types = append(types, f.Type)
		}
	}

	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "\npackage %s\n", in.Package)
	b.WriteString(emitImports(nil, types))

	for _, e := range in.Enums {
		fmt.Fprintf(&b, "\n// %s mirrors the PostgreSQL enum %s.\n", e.Name, e.DBName)
		fmt.Fprintf(&b, "type %s string\n", e.Name)
		fmt.Fprintf(&b, "\n// The %s values.\nconst (\n", e.DBName)
		for _, v := range e.Values {
			fmt.Fprintf(&b, "\t%s %s = %q\n", v.Name, e.Name, v.Value)
		}
		b.WriteString(")\n")
	}

	for _, m := range in.Models {
		fmt.Fprintf(&b, "\n// %s mirrors one row of the %s table.\n", m.Name, m.Table)
		fmt.Fprintf(&b, "type %s struct {\n", m.Name)
		for _, f := range m.Fields {
			fmt.Fprintf(&b, "\t%s %s\n", CamelCase(f.Name), f.Type)
		}
		b.WriteString("}\n")
	}
	return b.String()
}

// emitFile renders the queries of one source file.
func emitFile(pkg string, f SrcFile) string {
	base := []string{"context"}
	var types []string
	for _, q := range f.Queries {
		if q.Command == "iter" {
			base = append(base, "iter")
		}
		for _, p := range q.Params {
			types = append(types, p.Type)
		}
		if q.Ret.Kind == RetScalar {
			types = append(types, q.Ret.Type)
		}
		if q.Ret.Kind == RetRow {
			for _, fl := range q.Ret.Fields {
				types = append(types, fl.Type)
			}
		}
	}

	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "// Source: %s\n", f.Source)
	fmt.Fprintf(&b, "\npackage %s\n", pkg)
	b.WriteString(emitImports(base, types))

	for _, q := range f.Queries {
		emitQuery(&b, q)
	}
	return b.String()
}

// emitImports renders the import block for the base imports plus whatever
// the given type expressions require.
func emitImports(base []string, types []string) string {
	need := map[string]bool{}
	for _, imp := range base {
		need[imp] = true
	}
	for _, t := range types {
		if strings.Contains(t, "time.") {
			need["time"] = true
		}
		if strings.Contains(t, "json.") {
			need["encoding/json"] = true
		}
		if strings.Contains(t, "sql.") {
			need["database/sql"] = true
		}
	}
	if len(need) == 0 {
		return ""
	}

	imports := make([]string, 0, len(need))
	for imp := range need {
		imports = append(imports, imp)
	}
	sort.Strings(imports)

	if len(imports) == 1 {
		return fmt.Sprintf("\nimport %q\n", imports[0])
	}
	var b strings.Builder
	b.WriteString("\nimport (\n")
	for _, imp := range imports {
		fmt.Fprintf(&b, "\t%q\n", imp)
	}
	b.WriteString(")\n")
	return b.String()
}

// emitQuery renders one const + optional structs + the method.
func emitQuery(b *strings.Builder, q Query) {
	constName := lowerFirst(q.Name)
	fmt.Fprintf(b, "\nconst %s = %s\n", constName, backquote(q.SQL))

	// Params struct from four arguments up.
	useParamsStruct := len(q.Params) >= 4
	if useParamsStruct {
		fmt.Fprintf(b, "\n// %sParams holds the arguments of %s.\n", q.Name, q.Name)
		fmt.Fprintf(b, "type %sParams struct {\n", q.Name)
		for _, p := range q.Params {
			fmt.Fprintf(b, "\t%s %s\n", CamelCase(p.Name), p.Type)
		}
		b.WriteString("}\n")
	}

	if q.Ret.Kind == RetRow {
		fmt.Fprintf(b, "\n// %s is the result row of %s.\n", q.Ret.Type, q.Name)
		fmt.Fprintf(b, "type %s struct {\n", q.Ret.Type)
		for _, f := range q.Ret.Fields {
			fmt.Fprintf(b, "\t%s %s\n", CamelCase(f.Name), f.Type)
		}
		b.WriteString("}\n")
	}

	b.WriteString("\n")
	b.WriteString(wrapComment(q.Doc))

	taken := map[string]bool{
		"ctx": true, "row": true, "rows": true, "res": true,
		"err": true, "arg": true, "q": true,
	}
	var argNames []string
	for _, p := range q.Params {
		argNames = append(argNames, paramName(p.Name))
		taken[paramName(p.Name)] = true
	}

	// The argument list of the call site.
	callArgs := strings.Join(argNames, ", ")
	if useParamsStruct {
		var parts []string
		for _, p := range q.Params {
			parts = append(parts, "arg."+CamelCase(p.Name))
		}
		callArgs = strings.Join(parts, ", ")
	}
	if callArgs != "" {
		callArgs = ", " + callArgs
	}

	sig := signatureParams(q.Params, argNames, useParamsStruct, q.Name)
	itemVar := unique(itemVarName(q.Ret), taken)

	switch q.Command {
	case "exec":
		fmt.Fprintf(b, "func (q *Queries) %s(ctx context.Context%s) error {\n",
			q.Name, sig)
		fmt.Fprintf(b, "\t_, err := q.db.ExecContext(ctx, %s%s)\n", constName, callArgs)
		b.WriteString("\treturn err\n}\n")

	case "execrows":
		fmt.Fprintf(b, "func (q *Queries) %s(ctx context.Context%s) (int64, error) {\n",
			q.Name, sig)
		fmt.Fprintf(b, "\tres, err := q.db.ExecContext(ctx, %s%s)\n", constName, callArgs)
		b.WriteString("\tif err != nil {\n\t\treturn 0, err\n\t}\n")
		b.WriteString("\treturn res.RowsAffected()\n}\n")

	case "one":
		fmt.Fprintf(b, "func (q *Queries) %s(ctx context.Context%s) (%s, error) {\n",
			q.Name, sig, q.Ret.Type)
		fmt.Fprintf(b, "\trow := q.db.QueryRowContext(ctx, %s%s)\n", constName, callArgs)
		fmt.Fprintf(b, "\tvar %s %s\n", itemVar, q.Ret.Type)
		fmt.Fprintf(b, "\terr := row.Scan(%s)\n", scanArgs(itemVar, q.Ret))
		fmt.Fprintf(b, "\treturn %s, err\n}\n", itemVar)

	case "many":
		sliceVar := unique(sliceVarName(q.Name), taken)
		fmt.Fprintf(b, "func (q *Queries) %s(ctx context.Context%s) ([]%s, error) {\n",
			q.Name, sig, q.Ret.Type)
		fmt.Fprintf(b, "\trows, err := q.db.QueryContext(ctx, %s%s)\n", constName, callArgs)
		b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		b.WriteString("\tdefer rows.Close()\n\n")
		fmt.Fprintf(b, "\tvar %s []%s\n", sliceVar, q.Ret.Type)
		b.WriteString("\tfor rows.Next() {\n")
		fmt.Fprintf(b, "\t\tvar %s %s\n", itemVar, q.Ret.Type)
		fmt.Fprintf(b, "\t\tif err := rows.Scan(%s); err != nil {\n", scanArgs(itemVar, q.Ret))
		b.WriteString("\t\t\treturn nil, err\n\t\t}\n")
		fmt.Fprintf(b, "\t\t%s = append(%s, %s)\n", sliceVar, sliceVar, itemVar)
		b.WriteString("\t}\n")
		fmt.Fprintf(b, "\treturn %s, rows.Err()\n}\n", sliceVar)

	case "iter":
		zeroVar := unique("zero", taken)
		fmt.Fprintf(b, "func (q *Queries) %s(ctx context.Context%s) iter.Seq2[%s, error] {\n",
			q.Name, sig, q.Ret.Type)
		fmt.Fprintf(b, "\treturn func(yield func(%s, error) bool) {\n", q.Ret.Type)
		fmt.Fprintf(b, "\t\tvar %s %s\n", zeroVar, q.Ret.Type)
		fmt.Fprintf(b, "\t\trows, err := q.db.QueryContext(ctx, %s%s)\n", constName, callArgs)
		fmt.Fprintf(b, "\t\tif err != nil {\n\t\t\tyield(%s, err)\n\t\t\treturn\n\t\t}\n",
			zeroVar)
		b.WriteString("\t\tdefer rows.Close()\n\n")
		b.WriteString("\t\tfor rows.Next() {\n")
		fmt.Fprintf(b, "\t\t\tvar %s %s\n", itemVar, q.Ret.Type)
		fmt.Fprintf(b, "\t\t\tif err := rows.Scan(%s); err != nil {\n",
			scanArgs(itemVar, q.Ret))
		fmt.Fprintf(b, "\t\t\t\tyield(%s, err)\n\t\t\t\treturn\n\t\t\t}\n", zeroVar)
		fmt.Fprintf(b, "\t\t\tif !yield(%s, nil) {\n\t\t\t\treturn\n\t\t\t}\n", itemVar)
		b.WriteString("\t\t}\n")
		fmt.Fprintf(b, "\t\tif err := rows.Err(); err != nil {\n\t\t\tyield(%s, err)\n\t\t}\n",
			zeroVar)
		b.WriteString("\t}\n}\n")
	}
}

// signatureParams renders the parameter list after ctx, grouping consecutive
// parameters of the same type: "email, name string".
func signatureParams(params []Param, names []string, useStruct bool, queryName string) string {
	if len(params) == 0 {
		return ""
	}
	if useStruct {
		return ", arg " + queryName + "Params"
	}

	var parts []string
	for i := 0; i < len(params); {
		j := i
		for j+1 < len(params) && params[j+1].Type == params[i].Type {
			j++
		}
		parts = append(parts,
			strings.Join(names[i:j+1], ", ")+" "+params[i].Type)
		i = j + 1
	}
	return ", " + strings.Join(parts, ", ")
}

// scanArgs renders the Scan argument list for a result shape.
func scanArgs(varName string, ret Ret) string {
	if ret.Kind == RetScalar {
		return "&" + varName
	}
	var parts []string
	for _, f := range ret.Fields {
		parts = append(parts, "&"+varName+"."+CamelCase(f.Name))
	}
	return strings.Join(parts, ", ")
}

// itemVarName picks the per-row variable: v for scalars, r for row structs
// and the lowered first letter for models (var u User).
func itemVarName(ret Ret) string {
	switch ret.Kind {
	case RetModel:
		return strings.ToLower(ret.Type[:1])
	case RetRow:
		return "r"
	default:
		return "v"
	}
}

// sliceVarName picks the accumulator for :many from the query name:
// ListUsers collects into users. Anything unclear becomes items.
func sliceVarName(queryName string) string {
	rest := queryName
	for _, verb := range []string{"List", "Get", "Find", "Fetch", "Search", "Select", "All"} {
		if strings.HasPrefix(rest, verb) && len(rest) > len(verb) {
			rest = rest[len(verb):]
			break
		}
	}
	name := lowerFirst(rest)
	if name == "" || goKeywords[name] {
		return "items"
	}
	return name
}

// unique makes name collision-free against taken and reserves it.
func unique(name string, taken map[string]bool) string {
	for taken[name] {
		name += "_"
	}
	taken[name] = true
	return name
}

// backquote renders SQL as a raw string literal with the query on its own
// lines, falling back to a quoted literal when the text contains a backtick.
func backquote(sql string) string {
	if strings.Contains(sql, "`") {
		return strconv.Quote(sql)
	}
	return "`\n" + sql + "\n`"
}

// wrapComment renders text as // comment lines wrapped near 76 columns.
func wrapComment(text string) string {
	var b strings.Builder
	line := "//"
	for _, word := range strings.Fields(text) {
		if len(line)+1+len(word) > 76 && line != "//" {
			b.WriteString(line + "\n")
			line = "//"
		}
		line += " " + word
	}
	if line != "//" {
		b.WriteString(line + "\n")
	}
	return b.String()
}
